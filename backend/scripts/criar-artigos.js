// Cria as tabelas de artigos (sql/artigos.sql) e carrega data/artigos.json.
// Pode rodar mais de uma vez: tabelas que já existem e artigos já carregados são mantidos.
//
//   cd backend
//   node scripts/criar-artigos.js

require("dotenv").config({ path: require("path").join(__dirname, "..", ".env") });

const fs = require("fs");
const path = require("path");

const { conectarOracle } = require("../database");

const ddl = fs
  .readFileSync(path.join(__dirname, "..", "sql", "artigos.sql"), "utf8")
  .replace(/--.*$/gm, "")
  .split(";")
  .map((statement) => statement.trim())
  .filter(Boolean);

const artigos = require("../data/artigos.json");

async function tabelaExiste(connection, nome) {
  const resultado = await connection.execute(
    `SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME = :nome`,
    { nome },
  );
  return resultado.rows[0][0] > 0;
}

async function main() {
  const connection = await conectarOracle();

  try {
    for (const statement of ddl) {
      const tabela = statement.match(/CREATE TABLE (\w+)/i)?.[1];
      if (tabela && (await tabelaExiste(connection, tabela.toUpperCase()))) {
        console.log(`${tabela} já existe`);
        continue;
      }
      await connection.execute(statement);
      console.log(`${tabela} criada`);
    }

    let inseridos = 0;

    for (const artigo of artigos) {
      const existe = await connection.execute(
        `SELECT COUNT(*) FROM T_ARTICLE WHERE ID = :id`,
        { id: artigo.id },
      );
      if (existe.rows[0][0] > 0) continue;

      // Mantém os IDs originais do JSON
      await connection.execute(
        `INSERT INTO T_ARTICLE (ID, TITLE, DESCRIPTION, CONTENT, AUTHOR_NAME, CREATED_AT)
         VALUES (:id, :titulo, :descricao, :conteudo, :autor,
                 TO_TIMESTAMP(:criadoEm, 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"'))`,
        {
          id: artigo.id,
          titulo: artigo.title,
          descricao: artigo.description ?? null,
          conteudo: artigo.content,
          autor: artigo.authorName ?? null,
          criadoEm: artigo.createdAt,
        },
      );

      for (const tag of artigo.tags ?? []) {
        await connection.execute(
          `INSERT INTO T_ARTICLE_TAG (T_ARTICLE_ID, TAG) VALUES (:id, :tag)`,
          { id: artigo.id, tag },
        );
      }

      inseridos += 1;
    }

    // Próximos artigos continuam a numeração depois dos IDs do JSON
    await connection.execute(
      `ALTER TABLE T_ARTICLE MODIFY ID GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)`,
    );

    await connection.commit();
    console.log(`${inseridos} artigo(s) carregado(s); ${artigos.length - inseridos} já existia(m)`);
  } finally {
    await connection.close();
  }
}

main().catch((error) => {
  console.error("Erro ao criar artigos:", error);
  process.exit(1);
});

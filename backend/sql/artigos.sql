-- Artigos exibidos na Home do app (antes ficavam em src/data/articles.json).
-- Rodado por scripts/criar-artigos.js, que também carrega os artigos de data/artigos.json.

CREATE TABLE T_ARTICLE (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TITLE       VARCHAR2(200)  NOT NULL,
  DESCRIPTION VARCHAR2(500),
  CONTENT     VARCHAR2(4000) NOT NULL,
  AUTHOR_NAME VARCHAR2(120),
  CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE T_ARTICLE_TAG (
  T_ARTICLE_ID NUMBER       NOT NULL,
  TAG          VARCHAR2(60) NOT NULL,
  CONSTRAINT PK_ARTICLE_TAG PRIMARY KEY (T_ARTICLE_ID, TAG),
  CONSTRAINT FK_ARTICLE_TAG_ARTICLE FOREIGN KEY (T_ARTICLE_ID)
    REFERENCES T_ARTICLE (ID) ON DELETE CASCADE
);
